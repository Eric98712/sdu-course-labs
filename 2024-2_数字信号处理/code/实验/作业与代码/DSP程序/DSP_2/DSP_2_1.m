n = (-10:1:10); % 定义时间向量n，范围从-10到10，步长为1
x1 = (n >= 0);  % 生成单位阶跃序列x1，当n≥0时为1，否则为0
x2 = zeros(size(n)); % 初始化冲激序列x2为全零向量
x2(11) = 1;     % 在n=0的位置（索引11）设置冲激信号，值为1

% 定义滤波器系数：
a = [1, 0.75, 0.125]; % 分母系数（对应差分方程左侧y的系数）
b = [1, -1];           % 分子系数（对应差分方程右侧x的系数）

% 计算系统响应：
z1 = filter(b, a, x1); % 对阶跃输入x1进行滤波，得到阶跃响应z1
z2 = filter(b, a, x1); % 对冲激输入x2进行滤波，得到冲激响应z2

figure; % 创建新绘图窗口

% 绘制阶跃序列及其响应：
subplot(2, 2, 1);        % 创建2x2子图，选择第1个子图（左上）
stem(n, x1);             % 绘制阶跃序列离散图
title("阶跃序列");       % 设置标题

subplot(2, 2, 3);        % 选择第3个子图（左下）
stem(n, z1);             % 绘制阶跃响应离散图
title("阶跃序列响应");   % 设置标题

% 绘制冲激序列及其响应：
subplot(2, 2, 2);        % 选择第2个子图（右上）
stem(n, x2);             % 绘制冲激序列离散图
title("冲激序列");       % 设置标题

subplot(2, 2, 4);        % 选择第4个子图（右下）
stem(n, z2);             % 绘制冲激响应离散图
title("冲激序列响应");   % 设置标题

%解析部分求解
syms z Y n
% 定义传递函数 H(z)
H = (z - 1)/(z^2 + (3/4)*z + 1/8);

% 计算阶跃响应 Y(z) = H(z) * z/(z-1)
Y_z = H * z/(z - 1);
Y_z = simplify(Y_z);
H =  simplify(H);

% 逆Z变换求阶跃响应 s[n]
s_n = iztrans(Y_z, z, n);
s_n = simplify(s_n);
disp('阶跃响应 s[n]:');
disp(s_n);

% 逆Z变换求冲激响应 h[n]
h_n = iztrans(H, z, n);
h_n = simplify(h_n);
disp('冲激响应 h[n]:');
disp(h_n);

saveas(gcf, "DSP2_1_1.jpg"); % 将当前图形保存为JPG文件