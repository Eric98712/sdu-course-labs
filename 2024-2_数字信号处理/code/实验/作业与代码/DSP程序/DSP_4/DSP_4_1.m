% 定义时间序列和信号
n = 0 : 1 : 15;              % 生成0到15的离散时间序列，共16个采样点
x = cos(5*pi/16*n);         % 生成频率为5π/16的余弦信号，信号长度16点

% 计算16点DFT
N = 16;                     % 设置DFT点数为16（与信号长度相同）
N_l = 0 : 1 : 15;           % 定义DFT频点索引0到15
x_DFT_16 = abs(fft(x,N));   % 计算16点DFT并取模值（频域幅度谱）

% 绘制16点DFT
figure;                     % 创建新画布
subplot(3,1,1);             % 创建3行1列的子图，定位第1个
stem(N_l,x_DFT_16)          % 绘制连续曲线显示DFT幅度（建议改用stem更符合离散特性）
title("16点DFT变换");        % 添加标题
xlabel('频点索引k');         % 添加X轴标签（可补充单位：k=0对应0Hz，k=8对应π）
ylabel('|X(k)|');           % 添加Y轴标签

% 计算32点DFT
N = 32;                     % 设置DFT点数为32（通过补零扩展信号长度）
N_l = 0 : 1 : 31;           % 定义DFT频点索引0到31
x_DFT_32 = abs(fft(x,N));   % 计算32点DFT并取模值（更高频域分辨率）

% 绘制32点DFT
subplot(3,1,2);             % 定位第2个子图
stem(N_l,x_DFT_32);         % 绘制连续曲线（同样建议改用stem）
title("32点DFT变换");        % 添加标题
xlabel('频点索引k');         % 添加X轴标签（k=0~31对应0~2π）
ylabel('|X(k)|');           % Y轴标签

% 计算DTFT（离散时间傅里叶变换）
[H,w] = freqz(x,1,'whole'); % 通过FIR滤波器频率响应计算DTFT
                            % x: 分子多项式系数（信号本身）
                            % 1: 分母多项式（1表示无递归项）
                            % 'whole': 计算0~2π全频段
H_mag = abs(H);             % 取幅度响应（DTFT模值）

% 绘制DTFT
subplot(3,1,3);             % 定位第3个子图
plot(w,H_mag);              % 绘制连续幅度谱（DTFT为连续频域函数）
title("DTFT变换");           % 添加标题
xlabel('数字频率ω (rad)');   % X轴标签（可标注关键点：π对应Nyquist频率）
ylabel('|X(e^{jω})|');      % Y轴标签
xticks(0:pi/2:2*pi);        % 设置横坐标刻度（0, π/2, π, 3π/2, 2π）
xticklabels({'0','π/2','π','3π/2','2π'}); % 用π符号标注刻度

% 保存图形
saveas(gcf,"DSP4_1.jpg")    % 将当前画布保存为JPG图像，路径为工作目录/DSP4_1.jpg