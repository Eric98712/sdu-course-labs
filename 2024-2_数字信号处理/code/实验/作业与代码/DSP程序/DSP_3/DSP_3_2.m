% 定义传递函数的分子系数向量 num
num = [0.0528, 0.0797, 0.1295, 0.1295, 0.797, 0.0528];
% 定义传递函数的分母系数向量 den
den = [1, -1.8107, 2.4947, -1.8801, 0.9537, -0.2336];

% 将传递函数转换为零极点增益形式（ZPK模型）
% z: 零点位置，p: 极点位置，K: 系统增益
[z, p, K] = tf2zp(num, den)

% 创建新的图形窗口
figure;

% 左子图：绘制零极点分布图
subplot(1, 2, 1);
zplane(z, p);  % 绘制零点（圆圈）和极点（叉号）
title('零极点图');  % 添加标题
grid on;        % 显示网格

% 右子图：绘制幅频响应曲线
subplot(1, 2, 2);
% 定义传递函数的分子系数向量 num
num = [0.0528, 0.0797, 0.1295, 0.1295, 0.797, 0.0528];
% 定义传递函数的分母系数向量 den
den = [1, -1.8107, 2.4947, -1.8801, 0.9537, -0.2336];

% 将传递函数转换为零极点增益形式（ZPK模型）
% z: 零点位置，p: 极点位置，K: 系统增益
[z, p, K] = tf2zp(num, den)

% 创建新的图形窗口
figure;

% 左子图：绘制零极点分布图
subplot(1, 2, 1);
zplane(z, p);  % 绘制零点（圆圈）和极点（叉号）
title('零极点图');  % 添加标题
grid on;        % 显示网格

% 右子图：绘制幅频响应曲线
subplot(1, 2, 2);
% 计算完整单位圆（0 到 2π）的频率响应
% H: 复数频率响应，w: 0 到 2π 的 512 个均匀间隔频率点
[H, w] = freqz(num, den, 'whole');

% 将幅度响应转换为分贝单位（公式：20*log10|H|）
mag_dB = 20 * log10(abs(H));

% 绘制归一化频率响应曲线（横轴单位：π rad/sample）
plot(w / pi, mag_dB);  
xlabel('归一化频率 (\times \pi rad/sample)');  % 设置横轴标签
ylabel('幅度 (dB)');                          % 设置纵轴标签
title('幅频响应');                            % 添加标题
grid on;                                      % 显示网格

