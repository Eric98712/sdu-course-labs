	ORG 0000H
	AJMP MAIN
	ORG 0003H
	AJMP INTS
	ORG 000BH
	AJMP T0INT
	ORG 0100H
MAIN:
	MOV SP,#60H
	MOV TMOD,#01H
	MOV TH0,#0D8H
	MOV TL0,#0F0H
	CLR A
	MOV 30H,A
	MOV 31H,A
	MOV 32H,A
	MOV 33H,A
	MOV IE,#82H
	SETB EX0
	SETB PX0
	SETB IT0
	SETB TR0
	
	MOV 20H,#08H
	
MAIN_LOOP:
	SJMP MAIN_LOOP
	ORG 0300H
T0INT:
	MOV P0,#0FFH
	
	CLR C
	MOV 22H,#01H
	MOV A,20H
	SUBB A,22H
	JNZ NOV4
	MOV 20H,#08H
	SJMP NEXT0
NOV4:
	MOV A,20H
	RR A
	MOV 20H,A 

NEXT0:
	MOV P1,20H
	
	INC R0
	MOV A,R0
	ANL A,#03H
	MOV R0,A
	LCALL DISPLAY
	
	MOV TH0,#0D8H
	MOV TL0,#0F0H
	RETI
INTS:
	CLR C
	INC 30H
	MOV A,#0F6H
	ADD A,30H
	JNC NOV0
	INC 31H
	MOV 30H,#00H
NOV0:
	CLR C
	MOV A,#0F6H
	ADD A,31H
	JNC NOV1
	INC 32H
	MOV 31H,#00H
NOV1:
	CLR C
	MOV A,#0F6H
	ADD A,32H
	JNC NOV2
	INC 33H
	MOV 32H,#00H
NOV2:
	CLR C
	MOV A,#0F7H
	ADD A,33H
	JNC NOV3
	MOV 33H,#00H
NOV3:
	RETI
	
DISPLAY:
	MOV A,R0
	MOV 24H,A
	ADD A,#30H
	MOV R0,A
	MOV A,@R0
	MOV DPTR,#TABLE
	MOVC A,@A+DPTR
	MOV 21H,A
	MOV P0,21H
	MOV A,24H
	MOV R0,A
	RET
TABLE: DB 0C0H,0F9H,0A4H,0B0H,99H
	   DB 92H,82H,0F8H,80H,90H
 SJMP $
 END