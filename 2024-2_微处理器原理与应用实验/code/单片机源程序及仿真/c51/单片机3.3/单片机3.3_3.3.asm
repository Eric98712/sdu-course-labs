	ORG 0000H
	AJMP MAIN
	ORG 000BH
	AJMP T0INT
	ORG 0100H
MAIN:
	MOV SP,#60H
	MOV TMOD,#01H
	MOV TH0,#0D8H
	MOV TL0,#0F0H
	MOV IE,#82H
	SETB TR0
	
	
	MOV 20H,#01H
	
MAIN_LOOP:
	SJMP MAIN_LOOP
	ORG 0300H
T0INT:
	MOV P0,#0FFH
	MOV A,20H
	RL A
	MOV 20H,A
	MOV P2,20H
	
	INC R7
	MOV A,R7
	ANL A,#07H
	MOV R7,A
	LCALL DISPLAY
	
	
	MOV TH0,#0D8H
	MOV TL0,#0F0H
	RETI
	
DISPLAY:
	MOV A,R7
	MOV DPTR,#TABLE
	MOVC A,@A+DPTR
	MOV 21H,A
	MOV P0,21H
	RET
DELAY_1MS:
        MOV R6, #1       ; 外层循环次数 (100次)
DELAY_LOOP1:
        MOV R7, #248        ; 内层循环次数 (248次)
DELAY_LOOP2:
        DJNZ R7, DELAY_LOOP2 ; 2周期 × 248次 = 496μs
        DJNZ R6, DELAY_LOOP1 ; 外层循环控制
		RET
TABLE: DB 0F9H,0A4H,0B0H,99H
	   DB 92H,82H,0F8H,80H
 SJMP $
 END