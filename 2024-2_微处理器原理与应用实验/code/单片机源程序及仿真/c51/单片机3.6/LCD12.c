void LCD_Delay1ms(unsigned int c)//1ms
{
    unsigned char  a,b;
  for(; c>0; c--)
  {
      for(b=199; b>0; b--)
    {
          for(a=1; a>0; a--);
    }
  }
}
void LCD_Writecmd(unsigned char Command)
{
	RS = 0;
	RW = 0;
	EN = 0;
	LCD_DataPort=Command;
	EN = 1;
	LCD_Delay1ms(6);
	EN = 0;
}

void LCD_WriteData(unsigned char data_l)
{
	RS = 1;
	RW = 0;
	EN = 0;
	LCD_DataPort=data_l;
	EN = 1;
	LCD_Delay1ms(6);
	EN = 0;
}

void LCD_SelectScreen(unsigned int CS)
{
	if(CS == 0) 
	{
		CS1 = 1;
		CS2 = 0;
	}
	if(CS == 1) 
	{
		CS1 = 0;
		CS2 = 1;
	}
}

void LCD_init(void)
{
	RST = 1;
	LCD_Writecmd(0x30);
	LCD_Writecmd(0x0c);
	LCD_Writecmd(0x01);
	LCD_Delay1ms(5);
}

void SetLine(unsigned char page) //设置页码，页码为0~7
{
	page=0xb8|page;
	LCD_Writecmd(page);
}

void SetColumn(unsigned char column) //设置列，列号为0~63
{
	column=column&0x3f;
	column=0x40|column;
	LCD_Writecmd(column);
}


void SetStartLine(unsigned char startline) //设置起始行，行号为0~63
{
	startline=0xc0|startline;
	LCD_Writecmd(startline);
}

void Display(unsigned char ss,unsigned char page,unsigned char column,unsigned char number)
{
	int i;
	LCD_SelectScreen(ss); //ss 为屏号
	column=column&0x3f; //column 为列号
	SetLine(page);
	SetColumn(column);
	for(i=0;i<16;i++) //i 为一个字里面的各个列
	{
		LCD_WriteData(Hzk[i+32*number]); //number 为字号，
	//取第number 个汉字的第i 列数据编码值
	}
	SetLine(page+1); //显示第number 个汉字的下半部分
	SetColumn(column);
	for(i=0;i<16;i++)
	{
		LCD_WriteData(Hzk[i+32*number+16]);//取第number 个汉字的下半部分
	//第i 列数据编码值
	}
}