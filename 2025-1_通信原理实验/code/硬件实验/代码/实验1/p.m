Fs = 8000;          % 采样速率（PCM标准8kHz，奈奎斯特频率4kHz）
N = 1024;           % 采样点数
t = (0:N-1)/Fs;     % 时间向量
f0 = 1000;          % 正弦波频率
x = sin(2*pi*f0*t); % 生成正弦波信号

% 计算频谱
X = fft(x)/N;       % FFT并归一化
f = (0:N-1)*Fs/N;   % 频率轴（0~8kHz）

% 绘制频谱（只显示0~4kHz，避免镜像）
plot(f(1:N/2), 2*abs(X(1:N/2))); % 单边频谱，幅度翻倍修正
xlabel('频率 (Hz)'); ylabel('归一化幅度');
title('1000Hz正弦波频谱图');
grid on; xlim([0 4000]); % 限定显示0~4kHz