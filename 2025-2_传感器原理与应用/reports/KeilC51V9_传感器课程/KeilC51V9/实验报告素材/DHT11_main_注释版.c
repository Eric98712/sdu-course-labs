/****************************************************************************
 * 实验名称：基于 DHT11 的温湿度传感系统
 * 单片机型号：STC12LE5A60S2
 * 晶振频率：11.0592MHz
 * 功能描述：读取 DHT11 温湿度传感器数据，通过 LCD1602 液晶屏实时显示
 ****************************************************************************/

#include <reg51.h>      // 包含 8051 特殊功能寄存器定义（P0/P1/P2/P3、定时器等）
#include "typedef.h"    // 自定义类型定义：uchar = unsigned char, uint = unsigned int
#include "LCD1602.H"    // LCD1602 液晶显示驱动头文件（含 Lcd_Init、Write_String、Write_Char）
#include "DHT11.H"      // DHT11 温湿度传感器驱动头文件（含 RH() 读取函数、全局变量声明）

/****************************************************************************
 * 主函数
 * 说明：初始化 LCD1602 后进入无限循环，不断读取 DHT11 数据并刷新显示
 ****************************************************************************/
void main()
{
    Lcd_Init();         // 初始化 LCD1602 液晶模块
                        // 内部执行：设置 8 位数据接口、2 行显示、5x7 点阵、
                        //           开显示无光标、自动递增、清屏

    while(1)            // 主循环：不断读取传感器数据并更新 LCD 显示
    {
        RH();           // 调用 DHT11 读取函数，触发一次完整的温湿度采集
                        // 通信完成后，全局变量 T_data_H（温度整数）、
                        // RH_data_H（湿度整数）等被更新

        // ---------- LCD 第一行：显示湿度 ----------
        Write_String(0x80, "humidity:");
                        // 从 LCD 第一行首地址 0x80 开始写入字符串 "humidity:"
                        // 0x80 是 LCD1602 第一行第 1 列的 DDRAM 地址

        Write_Char(0x89, RH_data_H / 10 + 48);
                        // 在第一行第 10 列（0x89）显示湿度的十位数字
                        // RH_data_H/10 取出十位，+48 转换为 ASCII 码（'0'=48）

        Write_Char(0x8A, RH_data_H % 10 + 48);
                        // 在第一行第 11 列（0x8A）显示湿度的个位数字
                        // RH_data_H%10 取出个位，+48 转换为 ASCII 码

        Write_String(0x8B, "%rh");
                        // 在第一行第 12 列（0x8B）显示湿度单位 "%rh"

        // ---------- LCD 第二行：显示温度 ----------
        Write_String(0xC0, "temperature:");
                        // 从 LCD 第二行首地址 0xC0 开始写入字符串 "temperature:"
                        // 0xC0 是 LCD1602 第二行第 1 列的 DDRAM 地址

        Write_Char(0xCC, T_data_H / 10 + 48);
                        // 在第二行第 13 列（0xCC）显示温度的十位数字

        Write_Char(0xCD, T_data_H % 10 + 48);
                        // 在第二行第 14 列（0xCD）显示温度的个位数字

        Write_Char(0xCE, 0xDF);
                        // 在第二行第 15 列（0xCE）显示摄氏度符号 "°"
                        // 0xDF 是 LCD1602 字符发生器中的 "°" 符号编码

        Write_Char(0xCF, 'C');
                        // 在第二行第 16 列（0xCF）显示字母 "C"，组成 "°C"
    }
}
