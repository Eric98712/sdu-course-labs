/****************************************************************************
 * 实验名称：基于 HX711 的电子秤系统
 * 单片机型号：STC12LE5A60S2
 * 晶振频率：11.0592MHz
 * 功能描述：读取 HX711 24 位 A/D 转换器数据，计算重量并通过 LCD1602 显示
 ****************************************************************************/

#include "main.h"       // 主程序头文件（含 reg52.h 及函数声明）
#include "1602.h"        // LCD1602 液晶显示驱动头文件（含 lcd_init、write_command、write_data 等）
#include "HX711.h"       // HX711 称重传感器驱动头文件（含 HX711_Read、引脚定义）
#include "delay.h"       // 延时函数头文件（含 delay_ms 毫秒延时）
#include "uart.h"        // 串口通信头文件（含 uart_init、send_data，用于调试输出）

/*============================================================================
 * 全局变量定义
 *============================================================================*/
unsigned long HX711_Buffer = 0;          // HX711 读取缓冲区，存储原始 ADC 读数（24 位）
unsigned long Weight_Maopi = 0;          // 毛皮重量（空秤时的基准读数，去皮用）
unsigned long Weight_Shiwu = 0;          // 实物重量（去皮后的净重值）

/*============================================================================
 * 函数名称：Get_Maopi
 * 功能描述：获取毛皮重量（去皮操作）
 * 说    明：在空秤状态下调用，读取当前 HX711 数据作为零点基准，
 *           后续称重时减去此基准值即为物品净重
 *============================================================================*/
void Get_Maopi(void)
{
    HX711_Buffer = HX711_Read();         // 从 HX711 读取 24 位原始 ADC 数据
    Weight_Maopi = HX711_Buffer / 100;   // 除以 100 得到毛皮重量基准值
                                         // （对原始值做缩放，与 Get_Weight 保持一致）
}

/*============================================================================
 * 函数名称：Get_Weight
 * 功能描述：获取实物净重
 * 说    明：读取 HX711 数据，减去毛皮基准后通过校准系数换算为实际克数
 *============================================================================*/
void Get_Weight(void)
{
    HX711_Buffer = HX711_Read();         // 从 HX711 读取当前 24 位原始 ADC 数据
    HX711_Buffer = HX711_Buffer / 100;   // 缩放处理，与 Get_Maopi 保持相同缩放比

    if(HX711_Buffer >= Weight_Maopi)     // 判断当前读数是否大于等于毛皮基准
    {                                    // 若小于，说明传感器负漂移或未连接，不做更新
        Weight_Shiwu = HX711_Buffer;     // 暂存当前缩放后的读数
        Weight_Shiwu = Weight_Shiwu - Weight_Maopi;
                                         // 减去毛皮基准，得到净重（相对值）

        Weight_Shiwu = (unsigned int)((float)Weight_Shiwu / 3.95 + 0.05);
                                         // 校准换算：将 ADC 差值转换为实际克数
                                         // 3.95 为标定系数（每克对应的 ADC 变化量）
                                         // +0.05 用于四舍五入到整数克
    }
}

/*============================================================================
 * 主函数
 * 说    明：初始化外设 → 显示欢迎界面 → 去皮校准 → 循环称重并刷新 LCD
 *============================================================================*/
void main()
{
    uart_init();                         // 初始化 UART 串口（9600bps）
                                         // 用于调试时向 PC 发送重量数据

    lcd_init();                          // 初始化 LCD1602 液晶模块
                                         // 设置 8 位接口、2 行显示、清屏

    // ---------- 显示欢迎界面 ----------
    lcd_display_str(0, 1, "Welcome to use! ");
                                         // 在 LCD 第一行第 1 列（坐标 0,1）显示欢迎信息

    delay_ms(1000);                      // 延时 1000ms = 1 秒，让用户看清欢迎界面

    // ---------- 初始化称重显示界面 ----------
    lcd_clear();                         // 清屏，清除欢迎信息
    lcd_display_str(0, 1, "WEIGHT:         ");
                                         // 在第一行显示 "WEIGHT:" 标签（后面空格用于刷新数值）

    Get_Maopi();                         // 获取毛皮基准（去皮）
                                         // 此时称重托盘应为空，记录零点 ADC 值

    // ---------- 主循环：不断读取并显示重量 ----------
    while(1)
    {
        Get_Weight();                    // 获取当前实物净重（已去皮 + 校准换算）

        // ---------- 在 LCD 第二行显示重量数值 ----------
        write_command(0x80 + 0x40);      // 将 LCD 光标定位到第二行首地址
                                         // 0x80 是 DDRAM 基地址，+0x40 = 第二行第 1 列

        // 先写 7 个空格清除第二行旧数据（防止残留字符）
        write_data(' ');                 // 第 1 个空格
        write_data(' ');                 // 第 2 个空格
        write_data(' ');                 // 第 3 个空格
        write_data(' ');                 // 第 4 个空格
        write_data(' ');                 // 第 5 个空格
        write_data(' ');                 // 第 6 个空格
        write_data(' ');                 // 第 7 个空格

        write_command(0x80 + 0x40);      // 光标重新回到第二行首地址，准备显示重量

        // ---------- 逐位显示重量（高位为 0 时不显示，消除前导零） ----------
        if(Weight_Shiwu / 10000 != 0)    // 若万位（10kg 级）非零
            write_data(Weight_Shiwu / 10000 + 0x30);
                                         // 显示万位数字：除以 10000 取商，+0x30 转为 ASCII

        if(Weight_Shiwu / 1000 != 0)     // 若千位（1kg 级）非零（万位为零时千位可能为零）
            write_data((Weight_Shiwu % 10000) / 1000 + 0x30);
                                         // 显示千位数字：先取余 10000 去掉万位，再除以 1000

        if(Weight_Shiwu / 100 != 0)      // 若百位非零
            write_data(((Weight_Shiwu % 10000) % 1000) / 100 + 0x30);
                                         // 显示百位数字：逐层取余后除以 100

        if(Weight_Shiwu / 10 != 0)       // 若十位非零
            write_data((((Weight_Shiwu % 10000) % 1000) % 100) / 10 + 0x30);
                                         // 显示十位数字：逐层取余后除以 10

        // 个位始终显示（即使为 0 也显示）
        write_data((((Weight_Shiwu % 10000) % 1000) % 100) % 10 + 0x30);
                                         // 显示个位数字：最终取余 10，+0x30 转为 ASCII

        write_data(' ');                 // 数值后加一个空格分隔
        write_data('g');                 // 显示重量单位 "g"（克）
    }
}
